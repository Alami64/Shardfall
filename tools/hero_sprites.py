"""Builds the hero sprite sheet from assets/hero/source.webp (four views on a transparent background).

Writes assets/hero/hero.png (the four views side by side), src/render/heroFrames.ts (sizes and the
lines where each view is cut into moving pieces) and shots/hero-cuts.png (the cuts drawn, to check).

    npm run hero
"""
import os
from PIL import Image, ImageDraw

SRC = 'assets/hero/source.webp'
FIG_H = 180          # height of the tallest figure on the sheet, in pixels
PAD = 4
# Cut lines as a fraction of a figure's height, per view; None means measure it from the picture.
# Views: 0 front facing right, 1 front facing left, 2 back facing right, 3 back facing left.
OVERRIDE = {
    'sprout': [None, None, 0.12, 0.125],
    'neck': [None, None, 0.345, 0.345],
    'hem': [None, None, None, None],
}

src = Image.open(SRC).convert('RGBA')
W, H = src.size
# Clean the alpha: drop the faint haze, make the figures fully opaque, keep soft edges.
alpha = src.split()[3].point(lambda v: 0 if v < 40 else min(255, int((v - 40) * 255 / 180)))
src.putalpha(alpha)
solid = alpha.point(lambda v: 255 if v >= 128 else 0)

quads = [(0, 0, W // 2, H // 2), (W // 2, 0, W, H // 2), (0, H // 2, W // 2, H), (W // 2, H // 2, W, H)]
views = []
for q in quads:
    bb = solid.crop(q).getbbox()
    box = (q[0] + bb[0], q[1] + bb[1], q[0] + bb[2], q[1] + bb[3])
    views.append((src.crop(box), solid.crop(box)))

scale = FIG_H / max(v[0].size[1] for v in views)


def row_span(mask, y):
    px = mask.load()
    xs = [x for x in range(mask.size[0]) if px[x, y]]
    return (min(xs), max(xs)) if xs else None


def measure(mask, i):
    w, h = mask.size
    px = mask.load()
    width = lambda y: (lambda s: s[1] - s[0] + 1 if s else 0)(row_span(mask, y))
    # Feet: the middle of the bottom rows.
    spans = [row_span(mask, y) for y in range(int(h * 0.94), h)]
    spans = [s for s in spans if s]
    feet_x = sum((a + b) / 2 for a, b in spans) / len(spans)
    # Sprout: rows above the first one that is as wide as a skull.
    head_w = max(width(y) for y in range(int(h * 0.1), int(h * 0.4)))
    sprout = next(y for y in range(h) if width(y) > head_w * 0.5)
    if OVERRIDE['sprout'][i] is not None:
        sprout = int(OVERRIDE['sprout'][i] * h)
    stem = [row_span(mask, y) for y in range(max(0, sprout - 10), max(1, sprout - 2))]
    stem = [s for s in stem if s]
    sprout_x = sum((a + b) / 2 for a, b in stem) / len(stem) if stem else w / 2
    # Neck: where the figure widens from the skull into the capelet.
    ref = width(int(h * 0.3))
    neck = next((y for y in range(int(h * 0.32), int(h * 0.6)) if width(y) > ref * 1.12), int(h * 0.44))
    # Hem: the top of the gap between the legs, and the column of that gap.
    def gap(y):
        s = row_span(mask, y)
        if not s:
            return None
        best, run, at = 0, 0, None
        for x in range(s[0], s[1] + 1):
            if not px[x, y]:
                run += 1
                if run > best:
                    best, at = run, x - run // 2
            else:
                run = 0
        return (best, at) if best >= 5 else None
    rows = [(y, gap(y)) for y in range(int(h * 0.6), h)]
    runs, cur = [], []
    for y, g in rows:
        if g:
            cur.append((y, g[1]))
        elif cur:
            runs.append(cur)
            cur = []
    if cur:
        runs.append(cur)
    longest = max(runs, key=len) if runs else [(int(h * 0.82), int(feet_x))]
    hem = longest[0][0]
    cols = sorted(c for _, c in longest)
    split = cols[len(cols) // 2]
    if OVERRIDE['neck'][i] is not None:
        neck = int(OVERRIDE['neck'][i] * h)
    if OVERRIDE['hem'][i] is not None:
        hem = int(OVERRIDE['hem'][i] * h)
    return dict(feet_x=feet_x, sprout=sprout, sprout_x=sprout_x, neck=neck, hem=hem, split=split, h=h)


meas = [measure(v[1], i) for i, v in enumerate(views)]
reach = max(max(m['feet_x'], v[0].size[0] - m['feet_x']) for m, v in zip(meas, views))
cell_w = int(reach * scale + PAD) * 2
cell_h = FIG_H + PAD * 2
feet_y = cell_h - PAD

sheet = Image.new('RGBA', (cell_w * 4, cell_h), (0, 0, 0, 0))
frames = []
for i, ((img, _), m) in enumerate(zip(views, meas)):
    w, h = img.size
    small = img.resize((max(1, round(w * scale)), max(1, round(h * scale))), Image.LANCZOS)
    ox = round(cell_w / 2 - m['feet_x'] * scale)
    oy = feet_y - small.size[1]
    sheet.alpha_composite(small, (i * cell_w + ox, oy))
    frames.append(dict(
        top=oy,
        sprout=round(oy + m['sprout'] * scale), sproutX=round(ox + m['sprout_x'] * scale),
        neck=round(oy + m['neck'] * scale), hem=round(oy + m['hem'] * scale), split=round(ox + m['split'] * scale),
    ))

os.makedirs('assets/hero', exist_ok=True)
sheet.save('assets/hero/hero.png', optimize=True)

with open('src/render/heroFrames.ts', 'w') as f:
    f.write('// Generated by tools/hero_sprites.py (npm run hero). Do not edit by hand.\n')
    f.write('// Views: 0 front facing right, 1 front facing left, 2 back facing right, 3 back facing left.\n')
    f.write(f'export const HERO_CELL_W = {cell_w};\nexport const HERO_CELL_H = {cell_h};\n')
    f.write(f'export const HERO_FEET_Y = {feet_y};\nexport const HERO_FIG_H = {FIG_H};\n')
    f.write('/** Cut lines of each view, in sheet pixels inside its cell. */\n')
    f.write('export const HERO_FRAMES = [\n')
    for fr in frames:
        f.write('  { ' + ', '.join(f'{k}: {v}' for k, v in fr.items()) + ' },\n')
    f.write('];\n')

# A picture of the cuts, enlarged, to check by eye.
Z = 4
dbg = Image.new('RGBA', (sheet.size[0] * Z, sheet.size[1] * Z), (143, 197, 91, 255))
dbg.alpha_composite(sheet.resize(dbg.size, Image.NEAREST))
d = ImageDraw.Draw(dbg)
for i, fr in enumerate(frames):
    x0, x1 = i * cell_w * Z, (i + 1) * cell_w * Z
    for key, col in (('sprout', (255, 0, 255)), ('neck', (255, 60, 60)), ('hem', (40, 80, 255))):
        d.line([(x0, fr[key] * Z), (x1, fr[key] * Z)], fill=col, width=2)
    d.line([((i * cell_w + fr['split']) * Z, fr['hem'] * Z), ((i * cell_w + fr['split']) * Z, feet_y * Z)], fill=(40, 80, 255), width=2)
    d.ellipse([((i * cell_w + fr['sproutX']) * Z - 5, fr['sprout'] * Z - 5), ((i * cell_w + fr['sproutX']) * Z + 5, fr['sprout'] * Z + 5)], outline=(255, 0, 255), width=2)
    d.line([((i * cell_w + cell_w / 2) * Z, feet_y * Z - 12), ((i * cell_w + cell_w / 2) * Z, feet_y * Z + 12)], fill=(255, 255, 255), width=2)
os.makedirs('shots', exist_ok=True)
dbg.save('shots/hero-cuts.png')
print('sheet', sheet.size, 'cell', (cell_w, cell_h), 'bytes', os.path.getsize('assets/hero/hero.png'))
for fr in frames:
    print(fr)
